#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md from the lockfiles: every dependency with its licence.

Sources (CP10b item 3):
- web/package-lock.json and package-lock.json: npm records each package's licence.
- uv.lock: it records none, so the licence comes from the installed package's metadata
  (License-Expression, else its licence classifiers, else its License field), or, for the two
  packages uv installs only on other platforms, from RECORDED_LICENCES.
- The browser runtime: Pyodide's pyodide-lock.json names the shipped packages, and each shipped
  wheel's own METADATA gives its licence; pdf.js states its licence in its file header; Pyodide
  and the CPython standard library carry no metadata on disk, so theirs are in RECORDED_LICENCES.

Commands:
    third_party_notices.py            write the file
    third_party_notices.py --check    exit 1 if the file is out of date
"""

import argparse
import importlib.metadata
import json
import sys
import tomllib
import zipfile
from email.parser import Parser
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
NOTICES = REPO / "THIRD_PARTY_NOTICES.md"
VENDOR = REPO / "web" / "public" / "vendor"
PROJECT = "mpesa-core"
MAX_LICENCE_TEXT = 60
# Licences with no machine-readable source on this machine, each with where it was read.
RECORDED_LICENCES = {
    "colorama": ("BSD-3-Clause", "PyPI metadata; installed on Windows only"),
    "tzdata": ("Apache-2.0", "PyPI metadata; installed on Windows only"),
    "Pyodide": ("MPL-2.0", "the pyodide npm package's licence field"),
    "CPython standard library": ("PSF-2.0", "python.org licence for CPython"),
}
CLASSIFIER_NAMES = {
    "Apache Software License": "Apache-2.0",
    "BSD License": "BSD",
    "MIT License": "MIT",
    "Mozilla Public License 2.0 (MPL 2.0)": "MPL-2.0",
    "Python Software Foundation License": "PSF-2.0",
    "ISC License (ISCL)": "ISC",
}
APACHE_HEADER = "Licensed under the Apache License, Version 2.0"
HEADER = """# Third-party notices

Generated by `tools/release/third_party_notices.py` from `web/package-lock.json`,
`package-lock.json`, `uv.lock` and the runtime's `pyodide-lock.json`. Do not edit by hand: run
`uv run python tools/release/third_party_notices.py` after changing a dependency. CI fails when
this file is out of date. This project's own licence is not chosen yet (`LICENSE.pending`).
"""


def main():
    """Write or check the notices.

    Returns:
        Process exit code: 0 when written or up to date, 1 when ``--check`` finds it stale.

    Side Effects:
        Reads the lockfiles, installed metadata and vendored wheels; writes the notices file
        unless ``--check``; writes a line to stdout.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--path", type=Path, default=NOTICES)
    args = parser.parse_args()
    text = build_notices()
    if args.check:
        current = args.path.read_text(encoding="utf-8") if args.path.exists() else ""
        if current != text:
            print(f"third_party_notices: {args.path.name} is out of date; regenerate it")
            return 1
        print("third_party_notices: PASS (up to date)")
        return 0
    args.path.write_text(text, encoding="utf-8")
    print(f"third_party_notices: wrote {args.path.name}")
    return 0


def build_notices():
    """Build the notices' text.

    Returns:
        Markdown: what ships to the browser, then what is used in development only.

    Side Effects:
        Reads the lockfiles, installed metadata and vendored wheels.
    """
    web_lock = REPO / "web" / "package-lock.json"
    sections = [
        HEADER,
        "## Shipped to the browser\n",
        table(
            "The web app's production dependencies (web/package-lock.json)",
            npm_rows(web_lock, dev=False),
        ),
        table("The statement engine runtime (pyodide-lock.json and pdf.js)", runtime_rows()),
        "## Development only (never shipped)\n",
        table("web/package-lock.json, development dependencies", npm_rows(web_lock, dev=True)),
        table(
            "package-lock.json (lint and format tooling)",
            npm_rows(REPO / "package-lock.json", dev=True),
        ),
        table("uv.lock (the core's development and test tools)", python_rows()),
    ]
    return "\n".join(sections)


def table(heading, rows):
    """Render one section.

    Args:
        heading: The section's heading.
        rows: ``(name, version, licence)`` tuples.

    Returns:
        A Markdown section with a sorted, de-duplicated table.

    Side Effects:
        None.
    """
    lines = [f"### {heading}\n", "| Package | Version | Licence |", "|---|---|---|"]
    lines += [f"| {name} | {version} | {licence} |" for name, version, licence in sorted(set(rows))]
    return "\n".join(lines) + "\n"


def npm_rows(lockfile, *, dev):
    """List an npm lockfile's packages with the licence it records.

    Args:
        lockfile: Path of a version 3 package-lock.json.
        dev: True for development packages, False for production ones.

    Returns:
        ``(name, version, licence)`` tuples.

    Side Effects:
        Reads the lockfile.
    """
    packages = json.loads(lockfile.read_text(encoding="utf-8"))["packages"]
    return [
        (path.rsplit("node_modules/", 1)[-1], entry["version"], entry["license"])
        for path, entry in packages.items()
        if path and bool(entry.get("dev")) == dev
    ]


def python_rows():
    """List uv.lock's packages with their installed licence.

    Returns:
        ``(name, version, licence)`` tuples, the project itself left out.

    Side Effects:
        Reads uv.lock and installed package metadata.
    """
    lock = tomllib.loads((REPO / "uv.lock").read_text(encoding="utf-8"))
    return [
        (package["name"], package["version"], installed_licence(package["name"]))
        for package in lock["package"]
        if package["name"] != PROJECT
    ]


def installed_licence(name):
    """Read an installed package's licence.

    Args:
        name: The distribution name.

    Returns:
        Its licence, or the recorded one when it is not installed on this platform.

    Raises:
        LookupError: If it is neither installed nor recorded.

    Side Effects:
        Reads installed metadata.
    """
    try:
        return licence_of(importlib.metadata.metadata(name))
    except importlib.metadata.PackageNotFoundError as error:
        if name in RECORDED_LICENCES:
            return RECORDED_LICENCES[name][0]
        raise LookupError(f"{name} is not installed and has no recorded licence") from error


def licence_of(metadata):
    """Pick a licence from core metadata.

    Args:
        metadata: A package's METADATA, as a message.

    Returns:
        License-Expression, else the licence classifiers joined, else the License field's first
        line's licence name. A bare "BSD" classifier gives way to a License field that names the BSD
        variant ("BSD 3-Clause License").

    Side Effects:
        None.
    """
    if metadata.get("License-Expression"):
        return metadata["License-Expression"]
    classifiers = [
        CLASSIFIER_NAMES.get(name, name)
        for name in (
            classifier.rsplit(" :: ", 1)[-1]
            for classifier in metadata.get_all("Classifier") or []
            if classifier.startswith("License :: ")
        )
    ]
    first_line = ((metadata.get("License") or "").strip().splitlines() or [""])[0]
    if classifiers and not (classifiers == ["BSD"] and first_line.startswith("BSD ")):
        return " OR ".join(classifiers)
    # A free-text field may run on into notes and copyright lines; keep the licence's name.
    name = first_line.split(" (", 1)[0].split(",", 1)[0].strip()
    return name[:MAX_LICENCE_TEXT] or "UNKNOWN"


def runtime_rows():
    """List what the browser runtime ships: Pyodide, CPython's library, its packages and pdf.js.

    Returns:
        ``(name, version, licence)`` tuples.

    Side Effects:
        Reads the vendored lockfile, wheels and pdf.js; fails with FileNotFoundError if the
        runtime is not vendored (run tools/vendor.py fetch).
    """
    sys.path.insert(0, str(REPO / "tools"))
    import vendor  # noqa: PLC0415 - tools/vendor.py holds the shipped list; imported here only

    lock = json.loads((VENDOR / vendor.LOCK).read_text(encoding="utf-8"))
    rows = [
        ("Pyodide", vendor.PYODIDE_VERSION, RECORDED_LICENCES["Pyodide"][0]),
        (
            "CPython standard library",
            lock["info"]["python"],
            RECORDED_LICENCES["CPython standard library"][0],
        ),
        ("pdf.js", vendor.PDFJS_VERSION, pdfjs_licence(VENDOR / "pdfjs" / "pdf.min.mjs")),
    ]
    shipped_wheels = sorted(rel for rel in vendor.RUNTIME_SOURCES if rel.endswith(".whl"))
    for rel in shipped_wheels:
        metadata = wheel_metadata(VENDOR / rel)
        rows.append((metadata["Name"], metadata["Version"], licence_of(metadata)))
    return rows


def wheel_metadata(wheel):
    """Read a wheel's METADATA.

    Args:
        wheel: Path of the wheel.

    Returns:
        The metadata, as a message.

    Side Effects:
        Reads the wheel.
    """
    with zipfile.ZipFile(wheel) as archive:
        (member,) = [name for name in archive.namelist() if name.endswith(".dist-info/METADATA")]
        return Parser().parsestr(archive.read(member).decode("utf-8"))


def pdfjs_licence(path):
    """Read pdf.js's licence from its file header.

    Args:
        path: The vendored pdf.min.mjs.

    Returns:
        "Apache-2.0".

    Raises:
        ValueError: If the header does not state the Apache licence.

    Side Effects:
        Reads the start of the file.
    """
    with path.open(encoding="utf-8") as source:
        header = source.read(2000)
    if APACHE_HEADER not in header:
        raise ValueError(f"{path.name} does not state its licence in its header")
    return "Apache-2.0"


if __name__ == "__main__":
    sys.exit(main())
