#!/usr/bin/env python3
"""Guard 4: every fixture regenerates byte-identically from its manifest seed."""

import hashlib
import json
import sys
import tomllib
from pathlib import PurePosixPath

from _common import REPO, SYNTHETIC, iter_files, parse_root, report

sys.path.insert(0, str(REPO / "tools"))
from synth import generate as generator  # noqa: E402

MANIFEST = f"{SYNTHETIC}MANIFEST.toml"
IGNORED = {MANIFEST, f"{SYNTHETIC}.gitkeep"}


def main():
    """Check the fixture directory against its manifest.

    Returns:
        Process exit code: 1 on any mismatch, otherwise 0.

    Side Effects:
        Reads the tree and writes the report to stdout.
    """
    args = parse_root(__doc__).parse_args()
    return report("check_fixture_provenance", check(args.root), "provenance mismatch(es)")


def check(root):
    """Compare the manifest, the fixtures on disk and freshly generated bytes.

    Args:
        root: Repo root to check.

    Returns:
        Map of repo-relative path to mismatch count.

    Side Effects:
        Reads the manifest and fixtures.
    """
    path = root / MANIFEST
    if not path.is_file():
        return {MANIFEST: 1}
    manifest = tomllib.loads(path.read_text(encoding="utf-8"))
    findings = {}
    if manifest.get("generator_version") != generator.VERSION or "fake_password" not in manifest:
        findings[MANIFEST] = 1
    listed = set()
    checks = (
        (manifest.get("fixture", []), lambda rel, entry: _fixture_matches(root / rel, entry)),
        (manifest.get("recorded", []), lambda rel, entry: _recording_matches(root, rel, entry)),
    )
    for entries, matches in checks:
        for entry in entries:
            name = PurePosixPath(entry["path"])
            if ".." in name.parts or name.is_absolute():
                findings[MANIFEST] = findings.get(MANIFEST, 0) + 1
                continue
            rel = f"{SYNTHETIC}{name}"
            listed.add(rel)
            if not matches(rel, entry):
                findings[rel] = 1
    for rel in iter_files(root):
        if rel.startswith(SYNTHETIC) and rel not in listed and rel not in IGNORED:
            findings[rel] = 1
    return findings


def _fixture_matches(target, entry):
    """Check one fixture against its regenerated bytes and manifest hash.

    Args:
        target: Path of the fixture on disk.
        entry: Its manifest entry, with ``path``, ``seed`` and ``sha256``.

    Returns:
        True if the fixture exists and both comparisons agree.

    Side Effects:
        Reads the fixture.
    """
    if not target.is_file():
        return False
    actual = target.read_bytes()
    same_bytes = actual == generator.generate(entry["seed"], entry["path"])
    return same_bytes and hashlib.sha256(actual).hexdigest() == entry["sha256"]


def _recording_matches(root, rel, entry):
    """Check a file recorded from pdf.js, which the Python generator cannot regenerate.

    The PDF reader's own test proves it reproduces. This proves it is unedited and still describes
    the current source PDF.

    Args:
        root: Repo root to check.
        rel: Repo-relative path of the recorded file.
        entry: Its manifest entry, with ``source``, ``source_sha256``, ``engine`` and ``sha256``.

    Returns:
        True if the file and its source both match the manifest.

    Side Effects:
        Reads the recorded file and its source.
    """
    target = root / rel
    source = root / f"{SYNTHETIC}{entry['source']}"
    if not (target.is_file() and source.is_file()):
        return False
    recorded = target.read_bytes()
    if hashlib.sha256(recorded).hexdigest() != entry["sha256"]:
        return False
    if hashlib.sha256(source.read_bytes()).hexdigest() != entry["source_sha256"]:
        return False
    return json.loads(recorded).get("engine") == entry["engine"]


if __name__ == "__main__":
    sys.exit(main())
