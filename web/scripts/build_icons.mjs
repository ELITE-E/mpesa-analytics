#!/usr/bin/env node
// Writes src/components/icon-paths.ts: the SVG path of every Material Symbols icon the app names,
// outlined and filled, from the pinned @material-symbols/svg-400 pack (Apache-2.0). The app then
// draws icons as inline SVG: no icon font is fetched, nothing is requested at run time, and no style
// attribute is needed. The file is generated, never edited; it is gitignored.
//   node scripts/build_icons.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const WEB = join(import.meta.dirname, "..");
const SRC = join(WEB, "src");
const PACK = join(WEB, "node_modules/@material-symbols/svg-400/outlined");
const OUTPUT = join(SRC, "components/icon-paths.ts");
const PATH_DATA = /<path d="([^"]+)"\/>/;
// Names the app uses whose glyph the current pack files under another name.
const ALIASES = { file_download: "download" };

const named = icon_names();
const lines = [...named].sort().map((name) => {
  const file = ALIASES[name] ?? name;
  const outlined = path_of(`${file}.svg`);
  const filled = path_of(`${file}-fill.svg`) ?? outlined;
  return `  ${name}: [${JSON.stringify(outlined)}, ${JSON.stringify(filled)}],`;
});
writeFileSync(
  OUTPUT,
  [
    "// Generated by scripts/build_icons.mjs from @material-symbols/svg-400. Do not edit.",
    "",
    "/** Each icon's SVG path: outlined, then filled. The pack's viewBox is 0 -960 960 960. */",
    "export const ICON_PATHS: Record<string, readonly [string, string]> = {",
    ...lines,
    "};",
    "",
  ].join("\n"),
);
console.log(`icons: ${lines.length}`);

/**
 * Every string literal in the app's sources that names an icon in the pack.
 *
 * @returns {Set<string>} The icon names.
 */
function icon_names() {
  const available = new Set([
    ...readdirSync(PACK).map((file) => file.replace(/\.svg$/, "")),
    ...Object.keys(ALIASES),
  ]);
  const names = new Set();
  for (const file of source_files(SRC)) {
    for (const [, literal] of readFileSync(file, "utf8").matchAll(/"([a-z0-9_]+)"/g)) {
      if (available.has(literal)) names.add(literal);
    }
  }
  return names;
}

/**
 * The path data of one icon file, or null if the pack has no such file.
 *
 * @param {string} file The SVG's file name.
 * @returns {string|null} Its path's d attribute.
 */
function path_of(file) {
  try {
    return readFileSync(join(PACK, file), "utf8").match(PATH_DATA)[1];
  } catch {
    return null;
  }
}

/**
 * Every .ts and .tsx source file except the generated one.
 *
 * @param {string} directory Where to start.
 * @returns {string[]} The files' paths.
 */
function source_files(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? source_files(join(directory, entry.name))
      : /\.(ts|tsx)$/.test(entry.name) && entry.name !== "icon-paths.ts"
        ? [join(directory, entry.name)]
        : [],
  );
}
